public class subs {
    private String name;

    // Constructor that accepts a String argument
    public subs (String name) {
        this.name = name;
    }

    // Getter method (optional, but recommended to access the name)
    public String getName() {
        return name;
    }

    // Setter method (optional, to change the name later)
    public void setName(String name) {
        this.name = name;
    }
    
    
}
